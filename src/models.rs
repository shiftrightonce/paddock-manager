//! Persistence models.
//!
//! Each struct mirrors a physical table. The table name, id column and column
//! names all come from the `DirtyTable` derive, so `migrations` and the query
//! helpers refer to them through `table_name()`/`col_name_for_*` instead of
//! repeating string literals.
//!
//! Every column is declared as the physical type the SQLite schema already
//! uses (`TEXT`, `INTEGER`, `REAL`), because the app reads and writes rows
//! through `db::columns` rather than through the generated repository. Keeping
//! the declared types identical to the original schema means an existing
//! database and a freshly created one behave the same.

use dirtybase_db::types::{
    AutoGeneratedIntegerField, NumberField, OptionalIntegerField, OptionalNumberField,
    OptionalStringField, StringField,
};
use dirtybase_db_macro::DirtyTable;

/// `created_at`/`updated_at` are written by the app rather than by the database
/// so the format stays `YYYY-MM-DD HH:MM:SS` on old and new databases alike.

#[derive(Debug, Clone, Default, DirtyTable, serde::Serialize)]
pub struct Farm {
    pub id: AutoGeneratedIntegerField,
    pub name: StringField,
    pub location: StringField,
    pub weather_station: StringField,
    pub notes: StringField,
    pub created_at: StringField,
    pub updated_at: StringField,
}

